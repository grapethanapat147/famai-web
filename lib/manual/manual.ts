export type ManualBook = {
  key: string;
  file: string;
  title: string;
  subtitle: string;
};

export const MANUAL_BOOKS: readonly ManualBook[] = [
  ...(Object.keys(ROLE_MANUALS) as RoleCode[]).map((role) => ({
    key: role,
    file: `famai-${role}.pdf`,
    title: `คู่มือสำหรับ${ROLE_LABEL[role]}`,
    subtitle: `${screensForRole(role).length} หน้าที่บทบาทนี้เห็น`,
  })),
  { key: "flow", file: "famai-flow.pdf", title: "คู่มือผังกระบวนการ", subtitle: `${FLOWS.length} สายงานหลัก` },
];

export function isManualRole(key: string): key is RoleCode {
  return key in ROLE_MANUALS;
}

export function manualBook(key: string): ManualBook | undefined {
  return MANUAL_BOOKS.find((b) => b.key === key);
}

/** หน้าที่บทบาทนี้เห็น (เรียงตามลำดับเมนูจริง) */
export function screensForRole(role: RoleCode): MenuItem[] {
  return MENU_ITEMS.filter((item) => item.roles.includes(role));
}

/** หน้าที่บทบาทนี้ไม่เห็น พร้อมบอกว่าใครทำแทน */
export function hiddenScreensForRole(role: RoleCode): { item: MenuItem; owners: string[] }[] {
  return MENU_ITEMS.filter((item) => !item.roles.includes(role)).map((item) => ({
    item,
    owners: item.roles.map((r) => ROLE_LABEL[r as RoleCode] ?? r),
  }));
}

/** ชื่อกลุ่มเมนูของหน้านั้น (ไว้ใส่ในตารางคู่มือ) */
export function groupOfScreen(key: string): string {
  return MENU.find((g) => g.items.some((i) => i.key === key))?.group ?? "";
}

/** สายงานที่บทบาทนี้มีส่วนร่วม (admin ถือว่าเกี่ยวทุกสาย) */
export function flowsForRole(role: RoleCode): Flow[] {
  return FLOWS.filter((flow) => role === "admin" || flow.steps.some((s) => s.roles.includes(role)));
}

